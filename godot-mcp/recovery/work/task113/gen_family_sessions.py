class Batch(object):
    def __init__(self, batch, project, run_tag):
        self.batch = batch
        self.project = project
        self.run = "runs/_exercises/%s/%s" % (project, run_tag)
        self.calls = []
        self.manifest = []
        self.readback = []
        self.seq = 0

    def call(self, tool, port, args, intent="ok", note=""):
        self.seq += 1
        tag = "%s-%03d-%s" % (self.batch, self.seq, tool)
        call = {"tag": tag, "port": port, "tool": tool, "arguments": args}
        if note:
            call["note"] = note
        self.calls.append(call)
        self.manifest.append({"tag": tag, "tool": tool, "port": port,
                              "intent": intent, "note": note})
        return tag

    def sleep(self, port, ms, note):
        self.calls.append({"sleep_ms": ms, "port": port, "note": note})

    def readback_of(self, tool, witness, why, expect):
        self.readback.append({"tool": tool, "witness_tool": witness, "run": self.run,
                              "why": why, "expect": expect})

    def write(self):
        out_dir = os.path.join(SESS, self.project)
        if not os.path.isdir(out_dir):
            os.makedirs(out_dir)
        session = {"_comment": "TASK-113 batch %s -- %s" % (self.batch, self.project),
                   "game": self.project, "import": True, "calls": self.calls}
        with io.open(os.path.join(out_dir, "%s-session.json" % self.batch), "w",
                     encoding="utf-8", newline="\n") as h:
            h.write(json.dumps(session, ensure_ascii=False, indent=2) + "\n")
        with io.open(os.path.join(out_dir, "%s-manifest.json" % self.batch), "w",
                     encoding="utf-8", newline="\n") as h:
            h.write(json.dumps({"batch": self.batch, "project": self.project,
                                "calls": self.manifest, "readback": self.readback},
                               ensure_ascii=False, indent=2) + "\n")
        print("batch %s: %d calls, %d readback declarations -> %s"
              % (self.batch, len(self.calls), len(self.readback), out_dir))


