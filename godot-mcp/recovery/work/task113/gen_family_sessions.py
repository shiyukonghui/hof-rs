# The scene every exercise project starts from: a Node2D root with
#   * a NavigationRegion2D whose NavigationPolygon carries an outline (the bake
#     tool's own precondition: `generator_bake_from_source_geometry_data` reads
#     `NavigationPolygon::get_outline()`),
#   * a CharacterBody2D "Player" carrying a *drawn* Polygon2D (so a moved player
#     is a pixel change) and a NavigationAgent2D (the H4 move tool's agent path),
#   * a Node2D "Goal" the move tool can be aimed at,
