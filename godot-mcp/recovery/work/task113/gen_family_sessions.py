def wav_bytes(path, freq, seconds=0.25, rate=44100):
    """A small mono 16-bit RIFF WAVE: a sine (or silence when freq == 0)."""
    import math
    import struct
    frames = int(rate * seconds)
    data = bytearray()
    for i in range(frames):
        value = 0 if freq == 0 else int(12000 * math.sin(2.0 * math.pi * freq * i / rate))
        data += struct.pack("<h", value)
    out = bytearray()
    out += b"RIFF" + struct.pack("<I", 36 + len(data)) + b"WAVE"
    out += b"fmt " + struct.pack("<IHHIIHH", 16, 1, 1, rate, rate * 2, 2, 16)
    out += b"data" + struct.pack("<I", len(data)) + data
    with open(path, "wb") as handle:
        handle.write(bytes(out))


def prepare():
    for name, (_batch, gd) in PROJECTS.items():
        dst = os.path.join(EX, name)
        if not os.path.isdir(dst):
            shutil.copytree(SRC_PROJECT, dst)
            # The copied template's pong scenes are not this project's subject;
            # mk_probe.gd overwrites scenes/main.tscn right after the import.
            print("copied  %s" % dst)
        else:
            print("kept    %s (already there)" % dst)
        with io.open(os.path.join(dst, "mk_probe.gd"), "w", encoding="utf-8", newline="\n") as h:
            h.write(gd)
        print("wrote   %s/mk_probe.gd" % dst)
    audio_assets = os.path.join(EX, "ex_audio", "assets")
    if not os.path.isdir(audio_assets):
        os.makedirs(audio_assets)
    for i, freq in enumerate((440, 660, 880, 0, 220), 1):
        p = os.path.join(audio_assets, "tone%d.wav" % i)
        if not os.path.isfile(p):
            wav_bytes(p, freq)
        print("wav     %s (%d bytes)" % (p, os.path.getsize(p)))
    return 0


