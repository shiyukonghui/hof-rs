def build_h9():
    b = Batch("h9", "ex_rec", "h9-task113")
    b.call("running_game_get_scene_tree", "game", {}, "setup",
           "the running scene the recorder drives")
    b.call("running_game_get_node_properties", "game",
           {"node_path": "Player", "properties": ["position"]}, "setup",
           "read-back #1: the player's position before any input")
    # Five create -> replay(explicit) -> stop rounds, plus the two boundaries.
    for i in range(5):
        b.call("running_game_create_input_recording", "game", {},
               note="create call %d/5" % (i + 1))
        b.sleep("game", 120, "let the recorder node enter the tree")
        b.call("running_game_play_input_recording", "game",
               {"events": [{"type": "key", "keycode": "Right", "pressed": True, "time_ms": 0},
                           {"type": "key", "keycode": "Right", "pressed": False, "time_ms": 250}],
                "speed": 1.0},
               note="play call %d/5 with an explicit two-event recording; the injected keys are "
                    "what the recorder in the same run captures" % (i + 1))
        b.sleep("game", 900, "the replay injects its last event and the recorder sees both")
        b.call("running_game_stop_input_recording", "game", {},
               note="stop call %d/5: the events the recorder captured are returned" % (i + 1))
        b.sleep("game", 150, "settle")
    b.call("running_game_get_node_properties", "game",
           {"node_path": "Player", "properties": ["position"]}, "setup",
           "the player really moved while the recorded keys were down")
    b.call("running_game_set_node_property", "game",
           {"node_path": "Player", "property": "position", "value": {"x": 100.0, "y": 300.0}}, "setup",
           "reset the player so the replay's own motion is measurable")
    b.call("running_game_get_node_properties", "game",
           {"node_path": "Player", "properties": ["position"]}, "setup",
           "read-back #2: the player is back at (100,300) before the replay")
    # The replay that must be visible: no `events` argument -> the recording made
    # by the stop above is replayed into the running game.
    b.call("running_game_play_input_recording", "game", {"speed": 1.0},
           note="the create->stop->play chain: this replays the recording just stopped (no "
                "`events` argument)")
    b.sleep("game", 1200, "the replay injects the recorded keys; the player script moves on them")
    b.call("running_game_get_node_properties", "game",
           {"node_path": "Player", "properties": ["position"]}, "setup",
           "read-back #3: the replay moved the player (position.x > 100)")
    # boundaries
    b.call("running_game_create_input_recording", "game", {}, "setup",
           "start a recording that the boundary below then finds already running")
    b.call("running_game_create_input_recording", "game", {},
           "probe", "a recording is already running in this process")
    b.call("running_game_stop_input_recording", "game", {}, "setup", "close that session")
    b.call("running_game_play_input_recording", "game", {"events": []},
           "probe", "an empty event array is refused (nothing to replay)")
    b.call("running_game_stop_input_recording", "game", {},
           "edge", "stop with nothing recording is a documented success (there is nothing to collect)")
    b.call("running_game_get_node_properties", "game",
           {"node_path": "Player", "properties": ["position"]}, "setup",
           "read-back #4: the position after the boundary calls")

    b.readback_of("running_game_create_input_recording", "running_game_stop_input_recording",
                  "the stop call's answer carries the events of the session create started "
                  "(event_count > 0)", "\"recording\": false")
    b.readback_of("running_game_play_input_recording", "running_game_get_node_properties",
                  "the player's position after the create->stop->play chain is not the reset "
                  "(100,300): the replay really drove the game", "\"position\"")
    b.readback_of("running_game_stop_input_recording", "running_game_get_node_properties",
                  "the position read after the stop differs from the position read before the "
                  "session (the recorded keys moved the player)", "\"position\"")
    b.write()


